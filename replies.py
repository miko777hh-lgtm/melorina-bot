# جواب‌های اخیر برای جلوگیری از تکرار
_recent = {}


def normalize(text):
    text = text.lower().strip()

    text = re.sub(
        r"[؟?!،,.]+",
        " ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()


def get_ready_reply(text):
    """
    اگر پیام جواب آماده داشته باشد،
    همان لحظه جواب می‌دهد.
    """

    normalized = normalize(text)

    # اول عبارت‌های چندکلمه‌ای
    for category, words in KEYWORDS.items():

        for word in words:

            if normalize(word) in normalized:

                replies = REPLY_GROUPS[category]

                old = _recent.get(
                    category,
                    []
                )

                available = [
                    r for r in replies
                    if r not in old
                ]

                if not available:
                    available = replies

                reply = random.choice(
                    available
                )

                old.append(reply)

                _recent[category] = old[-5:]

                return reply

    return None
