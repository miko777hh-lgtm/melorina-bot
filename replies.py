# =========================================================
# جلوگیری از تکرار پشت سر هم
# =========================================================

_recent = defaultdict(lambda: deque(maxlen=6))


def _pick(chat_id: int, category: str) -> str:
    choices = READY.get(category, [])
    if not choices:
        return ""

    recent = _recent[chat_id]

    available = [x for x in choices if x not in recent]
    if not available:
        available = choices

    answer = random.choice(available)
    recent.append(answer)
    return answer


def get_ready_reply(chat_id: int, text: str) -> str | None:
    """
    فقط پیام‌های واقعاً رایج را اینجا بگیر.
    بقیه مستقیم می‌روند Gemini.
    """

    t = text.strip().lower()
    if not t:
        return None

    # سلام
    if re.fullmatch(r"(سلام|سلا+م|درود|هی|های|هلو)", t):
        return _pick(chat_id, "salam")

    # خوبی / چطوری
    if re.fullmatch(
        r"(خوبی|خوبی؟|چطوری|چطوری؟|حالت چطوره|حالت چطوره؟|چه خبر|چه خبر؟)",
        t
    ):
        return _pick(chat_id, "khubi")

    # تشکر
    if re.fullmatch(
        r"(مرسی|ممنون|ممنونم|دمت گرم|دمتگرم|تشکر|سپاس|سپاسگزارم)",
        t
    ):
        return _pick(chat_id, "merci")

    # خداحافظی
    if re.fullmatch(
        r"(خداحافظ|خدافظ|فعلا|فعلاً|بای|بای بای|شب بخیر|خوب بخوابی)",
        t
    ):
        return _pick(chat_id, "bye")

    # شوخی
    if re.fullmatch(r"(جوک|یه جوک|یک جوک|شوخی)", t):
        return _pick(chat_id, "joke")

    # بله
    if re.fullmatch(r"(آره|اره|بله|اوکی|باشه|حتما|حتماً)", t):
        return _pick(chat_id, "yes")

    # خیر
    if re.fullmatch(r"(نه|خیر|نخیر|نه ممنون)", t):
        return _pick(chat_id, "no")

    # هیچ جواب آماده‌ای نداریم
    return None
